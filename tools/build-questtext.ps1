# Builds Data/QuestText.lua (the quest text the Quests section shows for quests
# the player hasn't seen in game yet) from Efficient Games' EG Link dataset:
# https://github.com/JIVESCORP/eg-link-output-wowf (CC BY 4.0; the quest text
# itself is Blizzard's).
#
# Developer tool: not shipped in the release zip. Run from the addon folder:
#   powershell -ExecutionPolicy Bypass -File tools\build-questtext.ps1
# Optional: -Build 1.60.1.70959 (default: the newest "wowf" build).

param([string]$Build = "", [string]$Product = "wowf")

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$api = "https://api.github.com/repos/JIVESCORP/eg-link-output-wowf/contents/data/$Product"
$headers = @{ "User-Agent" = "build-questtext" }

if (-not $Build) {
    $builds = Invoke-RestMethod -Uri $api -Headers $headers | Where-Object { $_.type -eq "dir" } | ForEach-Object { $_.name }
    $Build = $builds | Sort-Object { [version]$_ } | Select-Object -Last 1
}
$url = "https://raw.githubusercontent.com/JIVESCORP/eg-link-output-wowf/main/data/$Product/$Build/quests.enUS.json"
Write-Host "Reading $url"
$tmp = Join-Path ([IO.Path]::GetTempPath()) "eglink-quests-$Build.json"
Invoke-WebRequest -Uri $url -Headers $headers -OutFile $tmp -UseBasicParsing
$json = [IO.File]::ReadAllText($tmp, [Text.Encoding]::UTF8) | ConvertFrom-Json

function Lua([string]$s) {
    if ([string]::IsNullOrWhiteSpace($s)) { return "nil" }
    $s = $s.Trim() -replace "`r", ""
    $s = $s.Replace("\", "\\").Replace('"', '\"').Replace("`n", "\n")
    return '"' + $s + '"'
}

$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine("-- Generated by tools/build-questtext.ps1 from EG Link ($Product $Build). Do not edit: run the script again.")
[void]$sb.AppendLine("-- Data from Efficient Games (https://efficient.games), licensed under CC BY 4.0;")
[void]$sb.AppendLine("-- trimmed to each quest's description, objectives text and XP tier. The quest text is Blizzard Entertainment's.")
[void]$sb.AppendLine("-- [questID] = { description, objectives, xpDifficulty 0-7 }")
[void]$sb.AppendLine("local FQB = Polestar and Polestar.FreeQuest and Polestar.FreeQuest.Browser")
[void]$sb.AppendLine("if not FQB then return end")
[void]$sb.AppendLine("FQB.QuestText = {")
$n = 0
foreach ($p in ($json.quests.PSObject.Properties | Sort-Object { [int]$_.Name })) {
    $q = $p.Value
    $d = Lua $q.description
    $o = Lua $q.objectivesText
    # The quest's XP tier (0-7): Blizzard's own measure of how big a quest is.
    $x = "nil"
    if ($q.rewards -and $null -ne $q.rewards.xpDifficulty) { $x = [string][int]$q.rewards.xpDifficulty }
    if ($d -eq "nil" -and $o -eq "nil" -and $x -eq "nil") { continue }
    [void]$sb.AppendLine("[$($p.Name)]={$d,$o,$x},")
    $n++
}
[void]$sb.AppendLine("}")
[void]$sb.AppendLine("FQB.QuestTextBuild = `"$Product $Build`"")

$out = Join-Path $root "Data\QuestText.lua"
New-Item -ItemType Directory -Force -Path (Split-Path $out) | Out-Null
[IO.File]::WriteAllText($out, $sb.ToString(), (New-Object Text.UTF8Encoding($false)))
$kb = [math]::Round((Get-Item $out).Length / 1KB)
Write-Host "Wrote $out : $n quests, $kb KB ($Product $Build)"
Remove-Item $tmp -ErrorAction SilentlyContinue
